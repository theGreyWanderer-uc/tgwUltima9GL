#!/usr/bin/env bash

set -u
cd "$(dirname "$0")" || exit 2
JOBS="${U9_JOBS:-20}"
if [ "${1:-}" = "-j" ] && [ -n "${2:-}" ]; then JOBS="$2"; shift 2; fi
case "${1:-}" in -j[0-9]*) JOBS="${1#-j}"; shift ;; esac
GCC="${1:-C:/msys64/mingw32/bin/gcc.exe}"
GCCDIR="$(dirname "$GCC")"
WINDRES="$GCCDIR/windres.exe"
if command -v cygpath >/dev/null 2>&1; then
    export PATH="$(cygpath -u "$GCCDIR"):$PATH"
else
    export PATH="$GCCDIR:$PATH"
fi

OUT=./out
GEN="$OUT/gen"
mkdir -p "$OUT" "$GEN"

CFLAGS="-m32 -O2 -Wall -Wextra -Wno-unused-parameter -std=gnu99 -static-libgcc -Iinclude -I. -I$GEN"

if [ -f ../include/u9renderer.h ]; then
    if ! cmp -s ../include/u9renderer.h include/u9renderer.h; then
        echo "ERROR: include/u9renderer.h has drifted from ../include/u9renderer.h" >&2
        diff -u ../include/u9renderer.h include/u9renderer.h | head -40 >&2
        echo "       copy the canonical one over it, or reconcile them." >&2
        exit 1
    fi
fi

PY="$(command -v python || command -v python3 || command -v py)"
if [ -n "$PY" ]; then
    "$PY" ../tools/check_ini_keys.py || exit 1
else
    echo "WARNING: no python - the ini key check did not run" >&2
fi

echo "toolchain:$("$GCC" -dumpmachine) $("$GCC" -dumpversion)"

VERSION="$(tr -d ' \r\n' < ../VERSION 2>/dev/null)"
if ! printf '%s' "$VERSION" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
    echo "ERROR: ../VERSION must hold MAJOR.MINOR.PATCH, found '$VERSION'" >&2
    exit 1
fi
VMAJ="${VERSION%%.*}"; VREST="${VERSION#*.}"; VMIN="${VREST%%.*}"; VPAT="${VREST#*.}"
GITHASH="$(git rev-parse --short HEAD 2>/dev/null || echo nogit)"
if [ -n "$(git status --porcelain --untracked-files=no 2>/dev/null)" ]; then
    GITHASH="$GITHASH.dirty"
fi
VERSION_FULL="$VERSION+$GITHASH"
{
    echo "/* Generated by u9gl/build.sh from ../VERSION - do not edit. */"
    echo "#define U9GL_VER_MAJOR $VMAJ"
    echo "#define U9GL_VER_MINOR $VMIN"
    echo "#define U9GL_VER_PATCH $VPAT"
    echo "#define U9GL_VERSION \"$VERSION\""
    echo "#define U9GL_VERSION_FULL \"$VERSION_FULL\""
} > "$GEN/u9gl_version.h"
echo "version: $VERSION_FULL"

res() {
    "$WINDRES" -F pe-i386 -I "$GEN" -I src/version -i "src/version/$1.rc" \
        -o "$GEN/$1.res.o" || exit 1
}

NOEXPORT="-Wl,--exclude-all-symbols"

U9LOG_SRC="
    src/injection/dllmain.c
    src/fix/fixes.c
    src/common/lifecycle.c
    src/common/u9time.c
    src/common/perfclock.c
    src/telemetry/transport.c
    src/telemetry/metrics_snapshot.c
    src/telemetry/publisher.c
    src/common/buildid.c
    src/common/symbols.c
    src/common/patchmgr.c
    src/common/claim.c
    src/injection/patch.c
    src/injection/config.c
    src/diag/hooks.c
    src/diag/crash.c
    src/diag/watch.c
    src/diag/hw.c
    src/diag/callsite.c
    src/diag/inline.c
    src/diag/factory.c
    src/diag/r5port.c
    src/diag/objstats.c
    src/diag/furniture.c
    src/fix/probes.c
    src/fix/teleprobe.c
    src/fix/pathprobe.c
    src/fix/bagprobe.c
    src/fix/birdprobe.c
    src/fix/doorfix.c
    src/fix/portalfix.c
    src/fix/shrinewatch.c
    src/fix/lightwatch.c
    src/fix/flyerfix.c
    src/fix/chasegrid.c
    src/fix/npcprobe.c
    src/fix/actorwatch.c
    src/fix/travelprobe.c
    src/fix/focusprobe.c
    src/fix/playerstats.c
    src/fix/playerwatch.c
    src/fix/playerset.c
    src/fix/breathfix.c
    src/fix/lettbook.c
    src/fix/trigprobe.c
    src/fix/meshprobe.c
    src/fix/meshstat.c
    src/fix/spellguard.c
    src/fix/clockfix.c
    src/fix/gold.c
    src/fix/freeplace.c
    src/gl/glprobe.c
    src/gl/glbackground.c
    src/gl/metrics.c
    src/gl/gpuprof.c
    src/gl/console.c
    src/gl/selfsample.c
    src/gl/npcscale.c
    src/gl/npccmd.c
    src/gl/questcmd.c
    src/gl/highway.c
    src/gl/regions.c
    src/gl/keys.c
    src/gl/glslots.c
    src/gl/glraster.c
    src/gl/glwbuffer.c
    src/gl/glpost.c
    src/gl/glwaterzones.c
    src/gl/gltwosided.c
    src/gl/glbackface.c
    src/gl/glanimdraw.c
    src/gl/glspaces.c
    src/gl/glshadow.c
    src/gl/glbloom.c
    src/gl/glbeam.c
    src/gl/glrays.c
    src/gl/glao.c
    src/gl/glreflect.c
    src/gl/glaa.c
    src/gl/glshot.c
    src/gl/gleffects.c
    src/gl/glsun.c
    src/gl/glmoon.c
    src/gl/glfog.c
    src/gl/glunder.c
    src/gl/gltex.c
    src/gl/glfeed.c
    src/texture/texoverride.c
    src/texture/texdecode.c
    src/diag/log.c"
OBJ="$OUT/obj"
rm -rf "$OBJ"; mkdir -p "$OBJ"
obj_of() { local o; for s in "$@"; do o="${s#src/}"; echo "$OBJ/${o//\//_}.o"; done; }
export GCC CFLAGS OBJ
echo "compiling $(printf '%s\n' $U9LOG_SRC | sort -u | wc -l) files, $JOBS at a time"
printf '%s\n' $U9LOG_SRC | sort -u | xargs -P "$JOBS" -I{} sh -c \
    'o="{}"; o="${o#src/}"; o=$(printf "%s" "$o" | tr / _); "$GCC" $CFLAGS -c "{}" -o "$OBJ/$o.o"' \
    || { echo "ERROR: a source file did not compile (see above)" >&2; exit 1; }

echo "building u9log.dll"
res u9log
"$GCC" $CFLAGS -shared -o "$OUT/u9log.dll" $(obj_of $U9LOG_SRC) \
    "$GEN/u9log.res.o" \
    -lopengl32 -lgdi32 $NOEXPORT || exit 1

echo "building u9inject.exe"
res u9inject
"$GCC" $CFLAGS -o "$OUT/u9inject.exe" src/injection/inject.c "$GEN/u9inject.res.o" || exit 1

echo "building dsound.dll (the loader)"
res dsound
"$GCC" $CFLAGS -shared -o "$OUT/dsound.dll" \
    src/loader/dsound_proxy.c src/loader/dsound.def "$GEN/dsound.res.o" || exit 1

echo "building u9sample.exe"
res u9sample
"$GCC" $CFLAGS -o "$OUT/u9sample.exe" ../tools/u9sample.c "$GEN/u9sample.res.o" -lwinmm || exit 1

mkdir -p "$OUT/sym"
for BIN in u9log.dll u9inject.exe dsound.dll u9sample.exe; do
    cp "$OUT/$BIN" "$OUT/sym/$BIN" || exit 1
    strip --strip-all "$OUT/$BIN" || { echo "ERROR: strip failed on $BIN" >&2; exit 1; }
    if [ -n "$(nm "$OUT/$BIN" 2>/dev/null)" ] || objdump -h "$OUT/$BIN" | grep -q -E '\.debug|\.stab'; then
        echo "ERROR: $BIN still carries symbols after strip" >&2
        exit 1
    fi
done
echo "stripped: symbol tables and debug sections removed (unstripped copies in $OUT/sym/)"

echo
echo "output:"
ls -l "$OUT"
echo
echo "sanity:"
objdump -f "$OUT/u9log.dll" | grep -E "file format|architecture" | sed 's/^/  /'
objdump -p "$OUT/u9log.dll" | grep "DLL Name" | sed 's/^/  /'

DS_WANT="1 DirectSoundCreate
2 DirectSoundEnumerateA
3 DirectSoundEnumerateW
4 DllCanUnloadNow
5 DllGetClassObject
6 DirectSoundCaptureCreate
7 DirectSoundCaptureEnumerateA
8 DirectSoundCaptureEnumerateW
9 GetDeviceID
10 DirectSoundFullDuplexCreate
11 DirectSoundCreate8
12 DirectSoundCaptureCreate8"
DS_HAVE="$(objdump -p "$OUT/dsound.dll" | tr -d '\r' \
    | sed -n '/^\[Ordinal\/Name Pointer\] Table/,/^$/p' \
    | sed -n 's/.*+base\[ *\([0-9]*\)\] *[0-9a-f]* \(.*\)$/\1 \2/p' | sort -n)"
if [ "$DS_HAVE" = "$DS_WANT" ]; then
    echo "  dsound.dll exports ordinals 1-12 as the system dsound.dll does"
else
    echo "ERROR: dsound.dll's export table does not match the system dsound.dll's:" >&2
    diff <(echo "$DS_WANT") <(echo "$DS_HAVE") >&2
    exit 1
fi

VERS_OUT="$(powershell.exe -NoProfile -Command 'foreach ($f in "u9log.dll","u9inject.exe","dsound.dll","u9sample.exe") { $v = (Get-Item (Join-Path "out" $f)).VersionInfo; "{0} {1} {2}" -f $f, $v.FileVersion, $v.ProductVersion }' | tr -d '\r')"
echo "  versions:"
printf '%s\n' "$VERS_OUT" | awk '{ printf "    %-13s %-8s %s\n", $1, $2, $3 }'
if printf '%s\n' "$VERS_OUT" | awk -v v="$VERSION" -v f="$VERSION_FULL" '$2 != v || $3 != f { bad = 1 } END { exit !bad }'; then
    echo "ERROR: a binary's version resource does not say $VERSION_FULL" >&2
    exit 1
fi

for INI in u9gl.ini u9gl.diag.ini; do
    if [ ! -f "$OUT/$INI" ]; then
        cp "$INI" "$OUT/$INI" && echo "  copied $INI -> $OUT/"
    elif ! cmp -s "$INI" "$OUT/$INI"; then
        echo "  NOTE $OUT/$INI differs from the source and was NOT updated."
        echo "       Delete it to take the current defaults, or diff to see what is missing."
    fi
done
